import type { Kit } from './parts';

/** 차: 두 바퀴 나무 전차에 올라탄 코뿔소. 투구를 쓰고 뒤에 팀 깃발을 꽂았다. */
export function rhino(k: Kit) {
  const skin = '#9aa4ae';
  const light = '#b8c0c8';

  // 전차 몸체 (나무 상자 + 테두리)
  k.box('wood', [0, 0.2, -0.03], [0.46, 0.2, 0.44], undefined, 0.03);
  k.box('darkWood', [0, 0.31, -0.03], [0.48, 0.03, 0.46], undefined, 0.012);
  // 앞 방패판 (팀 색 옻칠 + 금 장식)
  k.box('teamLacquer', [0, 0.28, 0.215], [0.44, 0.17, 0.035], [-0.12, 0, 0], 0.02);
  k.cyl('gold', [0, 0.285, 0.238], 0.05, 0.05, 0.012, [Math.PI / 2 - 0.12, 0, 0]);
  for (const s of [-1, 1]) k.cone('iron', [s * 0.16, 0.28, 0.25], 0.018, 0.06, [Math.PI / 2 - 0.12, 0, 0], 8);
  // 바퀴 (테·바큇살·굴대)
  for (const s of [-1, 1]) {
    k.within([s * 0.27, 0.17, -0.04], [0, Math.PI / 2, 0], () => {
      k.torus('darkWood', [0, 0, 0], 0.145, 0.028);
      k.torus('iron', [0, 0, 0], 0.17, 0.008);
      for (let i = 0; i < 4; i++) k.box('wood', [0, 0, 0], [0.018, 0.28, 0.018], [0, 0, (i * Math.PI) / 4], 0.005);
      k.cyl('bronze', [0, 0, 0.01], 0.035, 0.035, 0.05, [Math.PI / 2, 0, 0]);
    });
  }
  // 깃대와 깃발
  k.cyl('darkWood', [-0.18, 0.55, -0.2], 0.012, 0.012, 0.66);
  k.flat('team', [-0.18, 0.78, -0.2], [[0, 0.1], [0.22, 0.04], [0, -0.1]], 0.012, [0, 0.35, 0]);
  k.ball('gold', [-0.18, 0.89, -0.2], 0.022);

  // 코뿔소 (전차에서 상체만 보임)
  k.ball(skin, [0, 0.4, -0.05], [0.2, 0.19, 0.18]);
  for (const s of [-1, 1]) k.ball(skin, [s * 0.12, 0.35, 0.15], [0.055, 0.05, 0.06]);
  k.ball(skin, [0, 0.56, 0.06], [0.17, 0.15, 0.18]);
  k.ball(light, [0, 0.51, 0.2], [0.11, 0.09, 0.1]);
  k.cone('#f1e8d6', [0, 0.6, 0.25], 0.05, 0.18, [0.4, 0, 0]);
  k.cone('#f1e8d6', [0, 0.62, 0.15], 0.032, 0.08, [0.2, 0, 0]);
  for (const s of [-1, 1]) k.ball('eye', [s * 0.04, 0.5, 0.3], 0.013);
  k.eyes(0.1, 0.6, 0.19, 0.036, 0.3);
  k.cheeks(0.13, 0.52, 0.18);
  // 투구 + 술
  k.lathe('iron', [0, 0.62, 0.03], [
    [0, 0.13],
    [0.08, 0.12],
    [0.14, 0.07],
    [0.165, 0.0],
    [0.175, -0.01],
    [0, -0.01],
  ]);
  k.torus('gold', [0, 0.615, 0.03], 0.168, 0.012, [Math.PI / 2, 0, 0]);
  for (const s of [-1, 1]) k.cone(skin, [s * 0.14, 0.72, 0.02], 0.04, 0.08, [0, 0, -s * 0.5]);
  k.cyl('gold', [0, 0.77, 0.03], 0.012, 0.02, 0.04);
  k.cone('team', [0, 0.83, 0.03], 0.045, 0.1, [Math.PI, 0, 0]);
}
