import type { Kit } from './parts';

/** 사: 사모를 쓰고 관복을 입은 강아지 참모. 두루마리를 든다. */
export function dog(k: Kit) {
  const fur = '#f3e6d0';
  const brown = '#9a6437';

  // 관복
  k.lathe('team', [0, 0, 0], [
    [0, 0],
    [0.28, 0],
    [0.295, 0.03],
    [0.26, 0.18],
    [0.2, 0.33],
    [0.14, 0.4],
    [0, 0.42],
  ]);
  // 각대 (검은 띠에 금 장식)
  k.torus('black', [0, 0.22, 0], 0.247, 0.022, [Math.PI / 2 + 0.05, 0, 0]);
  for (const a of [-0.5, 0, 0.5]) k.ball('gold', [Math.sin(a) * 0.25, 0.22, Math.cos(a) * 0.25], 0.02);
  // 흉배 (가슴의 네모 수놓은 천)
  k.box('gold', [0, 0.3, 0.205], [0.13, 0.12, 0.012], [-0.4, 0, 0], 0.01);
  k.box('teamDark', [0, 0.302, 0.21], [0.09, 0.08, 0.01], [-0.4, 0, 0], 0.008);
  k.ball('paper', [0, 0.305, 0.216], [0.025, 0.02, 0.008], [-0.4, 0, 0]);
  // 소매·손·두루마리
  for (const s of [-1, 1]) {
    k.ball('team', [s * 0.17, 0.29, 0.1], [0.08, 0.11, 0.1], [0.7, 0, s * -0.3]);
    k.ball(fur, [s * 0.1, 0.25, 0.22], 0.045);
  }
  k.cyl('paper', [0, 0.255, 0.245], 0.032, 0.032, 0.26, [0, 0, Math.PI / 2]);
  for (const s of [-1, 1]) k.cyl('darkWood', [s * 0.14, 0.255, 0.245], 0.042, 0.042, 0.02, [0, 0, Math.PI / 2]);
  k.cyl('team', [0, 0.255, 0.245], 0.034, 0.034, 0.03, [0, 0, Math.PI / 2]);
  // 꼬리
  k.tube(brown, [[0, 0.12, -0.24], [0, 0.2, -0.33], [0, 0.3, -0.33]], 0.03);

  // 머리
  k.ball(fur, [0, 0.58, 0.03], 0.2);
  for (const s of [-1, 1]) k.ball(brown, [s * 0.19, 0.55, 0.0], [0.065, 0.15, 0.085], [0, 0, s * 0.28]);
  k.ball(brown, [0.085, 0.63, 0.17], [0.075, 0.075, 0.05]);
  k.ball('#fffaf0', [0, 0.52, 0.18], [0.09, 0.065, 0.07]);
  k.ball('eye', [0, 0.555, 0.245], [0.04, 0.03, 0.025]);
  k.eyes(0.08, 0.61, 0.19);
  k.cheeks(0.13, 0.53, 0.17);

  // 사모: 둥근 관 + 뒤의 높은 부분 + 양옆 날개
  k.cyl('black', [0, 0.74, -0.01], 0.13, 0.145, 0.08, undefined, 32);
  k.ball('black', [0, 0.78, -0.01], [0.13, 0.05, 0.13]);
  k.ball('black', [0, 0.82, -0.07], [0.105, 0.09, 0.075]);
  for (const s of [-1, 1]) {
    k.box('black', [s * 0.2, 0.8, -0.08], [0.18, 0.075, 0.014], [0, s * -0.15, s * 0.1], 0.03);
  }
}
