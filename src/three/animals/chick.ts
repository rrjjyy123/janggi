import type { Kit } from './parts';

/** 졸·병: 전립을 쓰고 창과 둥근 방패를 든 병아리 병사 */
export function chick(k: Kit) {
  const yellow = '#ffd449';
  const wing = '#f3bd2c';
  const orange = '#ff9420';

  for (const s of [-1, 1]) k.ball(orange, [s * 0.08, 0.02, 0.08], [0.055, 0.02, 0.07]);
  k.ball(yellow, [0, 0.27, 0], [0.23, 0.24, 0.22]);
  // 허리띠 (팀 색)
  k.torus('team', [0, 0.2, 0], 0.215, 0.024, [Math.PI / 2, 0, 0]);
  k.ball(yellow, [0, 0.47, 0.03], 0.16);
  k.cone(orange, [0, 0.45, 0.2], 0.04, 0.075, [Math.PI / 2, 0, 0]);
  k.eyes(0.065, 0.5, 0.155, 0.036);
  k.cheeks(0.11, 0.44, 0.14);

  // 전립 (넓은 챙 + 둥근 꼭대기 + 팀 색 끈과 상모)
  k.cyl('black', [0, 0.59, 0.0], 0.2, 0.21, 0.018, undefined, 36);
  k.ball('black', [0, 0.62, 0.0], [0.12, 0.09, 0.12]);
  k.torus('team', [0, 0.62, 0.0], 0.118, 0.016, [Math.PI / 2, 0, 0]);
  k.cyl('gold', [0, 0.72, 0.0], 0.012, 0.02, 0.04);
  k.ball('team', [0, 0.77, 0.0], [0.035, 0.05, 0.035]);

  // 오른쪽 날개: 창
  k.ball(wing, [0.21, 0.3, 0.06], [0.06, 0.11, 0.08], [0.4, 0, 0.5]);
  k.cyl('darkWood', [0.23, 0.45, 0.12], 0.012, 0.012, 0.9, [0.1, 0, 0]);
  k.cone('iron', [0.23, 0.93, 0.17], 0.028, 0.12, [0.1, 0, 0], 8);
  k.ball('team', [0.23, 0.84, 0.16], [0.03, 0.045, 0.03]);
  // 왼쪽 날개: 둥근 방패
  k.ball(wing, [-0.21, 0.28, 0.06], [0.06, 0.11, 0.08], [0.4, 0, -0.5]);
  k.within([-0.24, 0.27, 0.12], [0, -0.7, 0], () => {
    k.cyl('teamLacquer', [0, 0, 0], 0.13, 0.13, 0.03, [Math.PI / 2, 0, 0], 32);
    k.torus('gold', [0, 0, 0.016], 0.12, 0.01);
    k.ball('gold', [0, 0, 0.02], [0.035, 0.035, 0.02]);
  });
}
