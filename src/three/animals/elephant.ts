import type { Kit } from './parts';

/** 상: 등에 작은 가마를 얹고 이마 장식을 단 전투 코끼리 */
export function elephant(k: Kit) {
  const skin = '#8fa3bd';

  for (const sx of [-1, 1])
    for (const sz of [-1, 1]) {
      k.cyl(skin, [sx * 0.13, 0.08, sz * 0.11], 0.07, 0.075, 0.16);
      k.cyl('#e9e1d4', [sx * 0.13, 0.012, sz * 0.11], 0.074, 0.074, 0.022);
    }
  k.ball(skin, [0, 0.3, -0.04], [0.27, 0.24, 0.27]);
  // 덮개 천 + 금 테
  k.box('gold', [0, 0.45, -0.05], [0.42, 0.03, 0.4], undefined, 0.012);
  k.box('team', [0, 0.46, -0.05], [0.4, 0.04, 0.38], undefined, 0.015);
  for (const s of [-1, 1]) k.box('team', [s * 0.2, 0.38, -0.05], [0.02, 0.15, 0.34], [0, 0, s * 0.25], 0.01);
  // 가마 (나무 몸체 + 지붕 + 꼭지)
  k.box('darkWood', [0, 0.55, -0.07], [0.24, 0.13, 0.22], undefined, 0.015);
  for (const sx of [-1, 1]) for (const sz of [-1, 1]) k.cyl('gold', [sx * 0.11, 0.64, -0.07 + sz * 0.1], 0.01, 0.01, 0.08);
  k.cone('teamDark', [0, 0.74, -0.07], 0.2, 0.13, [0, Math.PI / 4, 0], 4);
  k.ball('gold', [0, 0.82, -0.07], 0.025);
  // 작은 깃발
  k.cyl('darkWood', [0.12, 0.8, -0.16], 0.008, 0.008, 0.26);
  k.flat('team', [0.12, 0.88, -0.16], [[0, 0.05], [0.12, 0.02], [0, -0.05]], 0.01, [0, 0.4, 0]);
  k.tube(skin, [[0, 0.25, -0.3], [0, 0.18, -0.36], [0, 0.1, -0.36]], 0.018);

  // 머리·귀
  k.ball(skin, [0, 0.52, 0.19], [0.2, 0.19, 0.18]);
  for (const s of [-1, 1]) {
    k.ball(skin, [s * 0.22, 0.54, 0.12], [0.15, 0.17, 0.035], [0, -s * 0.5, 0]);
    k.ball('pink', [s * 0.215, 0.54, 0.14], [0.1, 0.12, 0.02], [0, -s * 0.5, 0]);
  }
  // 코: 점점 가늘어지며 앞으로 말려 올라감
  k.tube(skin, [[0, 0.46, 0.33], [0, 0.36, 0.39], [0, 0.26, 0.42], [0, 0.22, 0.48], [0, 0.25, 0.53]], 0.045);
  k.ball(skin, [0, 0.46, 0.32], 0.06);
  for (const s of [-1, 1]) k.cone('#fffaf0', [s * 0.08, 0.4, 0.33], 0.022, 0.1, [2.0, 0, 0]);
  k.eyes(0.09, 0.58, 0.33, 0.038, 0.2);
  k.cheeks(0.14, 0.5, 0.32);
  // 이마 장식
  k.box('gold', [0, 0.66, 0.33], [0.16, 0.1, 0.02], [-0.5, 0, 0], 0.03);
  k.ball('teamLacquer', [0, 0.665, 0.345], 0.03);
  k.ball('team', [0, 0.59, 0.37], [0.02, 0.04, 0.02]);
}
