import type { Kit } from './parts';

/** 포: 어깨에 청동 대포를 멘 캥거루 포수. 머리띠를 두르고 불씨 막대를 든다. */
export function kangaroo(k: Kit) {
  const fur = '#c88a4d';
  const dark = '#a4692f';
  const cream = '#f1d3a4';

  // 발·꼬리·몸
  for (const s of [-1, 1]) k.ball(dark, [s * 0.1, 0.035, 0.08], [0.065, 0.035, 0.15]);
  k.tube(fur, [[0, 0.16, -0.14], [0, 0.07, -0.3], [0, 0.03, -0.42]], 0.045);
  k.ball(fur, [0, 0.33, 0], [0.2, 0.28, 0.19]);
  k.ball(cream, [0, 0.27, 0.1], [0.14, 0.16, 0.1]);
  // 주머니 속 아기
  k.ball(fur, [0, 0.39, 0.18], 0.06);
  for (const s of [-1, 1]) k.ball(fur, [s * 0.03, 0.46, 0.17], [0.018, 0.035, 0.013]);
  k.eyes(0.025, 0.405, 0.23, 0.014);
  // 탄띠 (어깨에서 허리로)
  k.torus('leather', [0, 0.36, 0.0], 0.21, 0.02, [Math.PI / 2 + 0.1, 0.6, 0]);
  k.box('gold', [-0.1, 0.24, 0.17], [0.05, 0.05, 0.02], [0, 0, 0.6], 0.008);

  // 머리
  k.ball(fur, [0, 0.72, 0.02], [0.17, 0.165, 0.17]);
  k.ball(cream, [0, 0.67, 0.16], [0.09, 0.075, 0.085]);
  k.ball('eye', [0, 0.7, 0.24], 0.026);
  for (const s of [-1, 1]) {
    k.ball(fur, [s * 0.08, 0.96, -0.02], [0.05, 0.14, 0.032], [0, 0, -s * 0.2]);
    k.ball('pink', [s * 0.08, 0.95, 0.005], [0.028, 0.09, 0.012], [0, 0, -s * 0.2]);
  }
  k.eyes(0.07, 0.76, 0.15, 0.04);
  k.cheeks(0.12, 0.68, 0.14);
  // 팀 색 머리띠 + 매듭
  k.torus('team', [0, 0.82, 0.0], 0.148, 0.02, [Math.PI / 2 - 0.2, 0, 0]);
  k.ball('team', [0.04, 0.84, -0.15], 0.028);
  k.tube('team', [[0.04, 0.83, -0.16], [0.08, 0.76, -0.22], [0.07, 0.68, -0.24]], 0.013);

  // 오른쪽 어깨의 청동 대포 (앞쪽으로 비스듬히 위를 겨눔)
  k.within([0.2, 0.58, -0.02], [-0.35, 0, 0], () => {
    k.lathe('bronze', [0, 0, -0.26], [
      [0, 0],
      [0.06, 0],
      [0.075, 0.03],
      [0.072, 0.1],
      [0.06, 0.14],
      [0.052, 0.48],
      [0.066, 0.5],
      [0.066, 0.55],
      [0.04, 0.55],
    ], [Math.PI / 2, 0, 0]);
    k.ball('bronze', [0, 0, -0.28], 0.045);
    for (const z of [-0.12, 0.05]) k.torus('bronze', [0, 0, z], 0.06, 0.012);
    k.cyl('eye', [0, 0, 0.29], 0.036, 0.036, 0.01, [Math.PI / 2, 0, 0]);
    // 포가 받침 끈
    k.torus('leather', [0, -0.01, -0.02], 0.068, 0.012, [0, Math.PI / 2, 0]);
  });
  // 대포를 잡은 두 손
  k.ball(fur, [0.13, 0.55, 0.13], 0.045);
  k.ball(fur, [0.25, 0.53, -0.06], 0.045);
  // 왼손의 불씨 막대
  k.ball(fur, [-0.17, 0.4, 0.12], 0.045);
  k.cyl('darkWood', [-0.18, 0.5, 0.13], 0.01, 0.01, 0.24, [0.15, 0, 0.1]);
  k.ball('ember', [-0.19, 0.62, 0.15], 0.025);
}
