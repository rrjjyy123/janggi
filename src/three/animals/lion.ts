import type { Kit } from './parts';

/** 궁: 익선관을 쓰고 곤룡포를 입은 사자 임금. 두 손으로 옥 홀(규)을 든다. */
export function lion(k: Kit) {
  const fur = '#e9a93f';
  const mane = '#a8541a';
  const cream = '#fbe2b0';

  // 곤룡포
  k.lathe('team', [0, 0, 0], [
    [0, 0],
    [0.31, 0],
    [0.325, 0.03],
    [0.3, 0.16],
    [0.25, 0.32],
    [0.2, 0.45],
    [0.14, 0.52],
    [0, 0.54],
  ]);
  // 옷깃·옥대
  k.torus('gold', [0, 0.29, 0], 0.262, 0.028, [Math.PI / 2, 0, 0]);
  for (let i = 0; i < 6; i++) {
    const a = (i / 6) * Math.PI * 2;
    k.ball('jade', [Math.sin(a) * 0.268, 0.29, Math.cos(a) * 0.268], 0.025);
  }
  k.torus('teamDark', [0, 0.49, 0.02], 0.13, 0.03, [Math.PI / 2 + 0.2, 0, 0]);
  // 가슴의 금색 둥근 보
  k.cyl('gold', [0, 0.38, 0.215], 0.085, 0.085, 0.014, [Math.PI / 2 - 0.42, 0, 0]);
  k.cyl('teamDark', [0, 0.384, 0.222], 0.058, 0.058, 0.01, [Math.PI / 2 - 0.42, 0, 0]);
  // 소매와 손, 옥 홀
  for (const s of [-1, 1]) {
    k.ball('team', [s * 0.19, 0.37, 0.08], [0.085, 0.13, 0.09], [0.5, 0, s * -0.4]);
    k.ball(fur, [s * 0.055, 0.31, 0.25], 0.05);
  }
  k.box('jade', [0, 0.42, 0.265], [0.06, 0.26, 0.022], [-0.28, 0, 0], 0.01);
  // 꼬리
  k.tube(fur, [[0, 0.1, -0.28], [0, 0.18, -0.4], [0.05, 0.3, -0.44]], 0.022);
  k.ball(mane, [0.05, 0.32, -0.44], 0.055);

  // 머리: 갈기 → 얼굴
  k.ball(mane, [0, 0.72, -0.06], [0.3, 0.3, 0.2]);
  for (let i = 0; i < 14; i++) {
    const a = (i / 14) * Math.PI * 2;
    k.ball(mane, [Math.cos(a) * 0.27, 0.72 + Math.sin(a) * 0.27, -0.03], 0.085);
  }
  k.ball(fur, [0, 0.72, 0.04], 0.215);
  for (const s of [-1, 1]) k.ball(fur, [s * 0.16, 0.88, 0.0], 0.055);
  k.ball(cream, [0, 0.655, 0.2], [0.11, 0.075, 0.07]);
  k.ball('eye', [0, 0.69, 0.255], [0.036, 0.026, 0.02]);
  k.eyes(0.08, 0.76, 0.2);
  k.cheeks(0.14, 0.67, 0.19);

  // 익선관: 검은 관 + 뒤로 솟은 부분 + 위로 선 두 날개, 금테
  k.cyl('black', [0, 0.92, -0.01], 0.15, 0.165, 0.1, undefined, 32);
  k.ball('black', [0, 0.97, -0.01], [0.15, 0.06, 0.15]);
  k.ball('black', [0, 1.0, -0.11], [0.12, 0.1, 0.07]);
  for (const s of [-1, 1]) k.box('black', [s * 0.07, 1.1, -0.14], [0.07, 0.11, 0.018], [0.15, 0, s * -0.12], 0.02);
  k.torus('gold', [0, 0.875, -0.01], 0.163, 0.014, [Math.PI / 2, 0, 0]);
  k.ball('gold', [0, 0.93, 0.15], 0.028);
}
