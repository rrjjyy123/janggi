import type { Kit } from './parts';

/** 마: 마갑 천과 안장을 얹고 깃털 투구를 쓴 기마 조랑말 */
export function pony(k: Kit) {
  const coat = '#a3673c';
  const hair = '#3a2414';
  const muzzle = '#e6c29c';

  // 다리·발굽
  for (const sx of [-1, 1])
    for (const sz of [-1, 1]) {
      k.cyl(coat, [sx * 0.11, 0.1, sz * 0.12], 0.05, 0.048, 0.16);
      k.cyl('eye', [sx * 0.11, 0.022, sz * 0.12], 0.055, 0.06, 0.045);
    }
  k.tube(hair, [[0, 0.36, -0.27], [0, 0.3, -0.36], [0, 0.18, -0.38]], 0.04);
  // 몸통
  k.ball(coat, [0, 0.32, -0.02], [0.21, 0.19, 0.28]);
  // 마갑 천 (팀 색) + 금 테
  k.cyl('team', [0, 0.3, -0.03], 0.225, 0.235, 0.15, undefined, 32);
  k.torus('gold', [0, 0.225, -0.03], 0.235, 0.012, [Math.PI / 2, 0, 0]);
  for (let i = 0; i < 8; i++) {
    const a = (i / 8) * Math.PI * 2;
    k.cone('gold', [Math.sin(a) * 0.235, 0.205, -0.03 + Math.cos(a) * 0.235], 0.02, 0.04, [Math.PI, 0, 0], 8);
  }
  // 안장
  k.box('leather', [0, 0.49, -0.05], [0.2, 0.05, 0.22], undefined, 0.02);
  k.box('leather', [0, 0.52, -0.14], [0.18, 0.06, 0.04], undefined, 0.02);
  for (const s of [-1, 1]) k.torus('gold', [s * 0.2, 0.35, -0.04], 0.03, 0.007, [0, Math.PI / 2, 0]);

  // 목과 머리
  k.ball(coat, [0, 0.55, 0.13], [0.12, 0.17, 0.12], [0.5, 0, 0]);
  k.ball(coat, [0, 0.7, 0.19], [0.15, 0.15, 0.16]);
  k.ball(muzzle, [0, 0.62, 0.32], [0.1, 0.085, 0.1]);
  for (const s of [-1, 1]) k.ball('eye', [s * 0.04, 0.63, 0.41], 0.014);
  k.eyes(0.085, 0.74, 0.3, 0.04, 0.25);
  k.cheeks(0.12, 0.66, 0.28);
  // 굴레
  k.torus('leather', [0, 0.63, 0.31], 0.1, 0.012, [0, 0, 0]);
  k.ball('gold', [0.1, 0.63, 0.31], 0.018);
  k.ball('gold', [-0.1, 0.63, 0.31], 0.018);
  // 갈기
  for (let i = 0; i < 4; i++) k.ball(hair, [0, 0.78 - i * 0.08, 0.1 - i * 0.06], [0.045, 0.07, 0.07]);
  // 투구 (쇠 + 금테 + 깃털)
  for (const s of [-1, 1]) k.cone(coat, [s * 0.075, 0.86, 0.17], 0.035, 0.09, [0, 0, -s * 0.3]);
  k.lathe('iron', [0, 0.79, 0.18], [
    [0, 0.1],
    [0.07, 0.09],
    [0.12, 0.05],
    [0.14, 0],
    [0, 0],
  ]);
  k.torus('gold', [0, 0.79, 0.18], 0.14, 0.01, [Math.PI / 2, 0, 0]);
  k.cyl('gold', [0, 0.9, 0.18], 0.01, 0.015, 0.04);
  k.ball('team', [0, 0.99, 0.15], [0.035, 0.1, 0.035], [-0.4, 0, 0]);
}
